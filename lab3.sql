DO $$
DECLARE t text[];
BEGIN
  FOREACH t SLICE 1 IN ARRAY ARRAY[
    ['airline','airline_id'], ['airport','airport_id'], ['passengers','passenger_id'],
    ['flights','flight_id'], ['booking','booking_id'], ['booking_flight','booking_flight_id'],
    ['baggage','baggage_id'], ['baggage_check','baggage_check_id'],
    ['boarding_pass','boarding_pass_id'], ['security_check','security_check_id']]
  LOOP
    EXECUTE format('SELECT setval(pg_get_serial_sequence(%L, %L), (SELECT COALESCE(MAX(%I),0)+1 FROM %I), false)',
                   t[1], t[2], t[2], t[1]);
  END LOOP;
END $$;

