-- TASK 5. Delete all flights whose arrival is in 2024
--         (actual arrival; use sch_arrival_time if your teacher means scheduled)
--         Child rows (booking, booking_flight, baggage, ...) must be deleted first,
--         otherwise the foreign keys block the delete.
-- =====================================================================
CREATE TEMP TABLE del_flights AS
    SELECT flight_id FROM flights
    WHERE act_arrival_time >= '2024-01-01' AND act_arrival_time < '2025-01-01';

CREATE TEMP TABLE del_bookings AS
    SELECT booking_id FROM booking      WHERE flight_id IN (SELECT flight_id FROM del_flights)
    UNION
    SELECT booking_id FROM booking_flight WHERE flight_id IN (SELECT flight_id FROM del_flights);

DELETE FROM baggage_check  WHERE booking_id IN (SELECT booking_id FROM del_bookings);
DELETE FROM baggage        WHERE booking_id IN (SELECT booking_id FROM del_bookings);
DELETE FROM boarding_pass  WHERE booking_id IN (SELECT booking_id FROM del_bookings);
DELETE FROM booking_flight WHERE booking_id IN (SELECT booking_id FROM del_bookings)
                              OR flight_id  IN (SELECT flight_id  FROM del_flights);
DELETE FROM booking        WHERE booking_id IN (SELECT booking_id FROM del_bookings);
DELETE FROM flights        WHERE flight_id  IN (SELECT flight_id  FROM del_flights);

SELECT count(*) AS flights_arriving_2024 FROM flights
WHERE act_arrival_time >= '2024-01-01' AND act_arrival_time < '2025-01-01';   -- must be 0

